// 惰性 fetch（探针只调 validateAgentPolicy，构造期与探针期都不发网络请求）。
const PROBE_FETCH_IMPL = async () => ({ ok: true, status: 200, json: async () => ({}) });
const PROBE_PROVIDER = {
  protocol: "anthropic-compatible",
  baseUrl: "https://gen-certification-probe.invalid",
  apiKeyEnv: "GEN_CERTIFICATION_PROBE_KEY",
};
// 探针占位值（与 POLICY_PROBE_BASES 同款纪律：一眼假，无真实路径/主机/凭据名）。
const PROBE_MODEL_ID = "gen-certification-probe-model";
const PROBE_PROVIDER_ID = "gen-certification-probe";
const PROBE_CONTEXT_WINDOW = 1000000;

/** 派生法：全过=支持 / 全拒=不支持 / 混合=条件。 */
function deriveVerdict(results) {
  if (results.every(Boolean)) return "支持";
  if (results.some(Boolean)) return "条件";
  return "不支持";
}

function probePasses(backend, agent) {
  try {
    backend.validateAgentPolicy(agent);
    return true;
  } catch {
    return false;
  }
}

/** kimi 档位门的模型绑定事实源：KIMI_K3_MODEL_ID 源常量。 */
function extractKimiK3ModelId() {
  const src = readFileSync(join(REPO_ROOT, "src", "backends", "kimiCode.js"), "utf8");
  const id = src.match(/const KIMI_K3_MODEL_ID = "([^"]+)"/)?.[1];
  if (!id) {
    throw new Error("gen-certification: src/backends/kimiCode.js must define KIMI_K3_MODEL_ID (reasoning probe companion source)");
  }
  return id;
}

// opencode-serve 角色合同版本门事实源：OPENCODE_NATIVE_SYSTEM_MIN_VERSION 源常量。
function extractOpencodeMinVersion() {
  const src = readFileSync(join(REPO_ROOT, "src", "backends", "opencodeServe.js"), "utf8");
  const raw = src.match(/OPENCODE_NATIVE_SYSTEM_MIN_VERSION = Object\.freeze\(\[([^\]]*)\]\)/)?.[1];
  if (!raw) {
    throw new Error("gen-certification: src/backends/opencodeServe.js must define OPENCODE_NATIVE_SYSTEM_MIN_VERSION");
  }
  const [maj, min] = [...raw.matchAll(/\d+/g)].map((m) => m[0]);
  return `${maj}.${min}`;
}

/**
 * 底稿校验（生成期红，不静默渲染）：底稿必须通过该 backend 的
 * validateAgentPolicy（否则每格探针都从非法配置出发，"不支持"会撞在缺别的
 * 必填字段上——归不到被测项）；且必须最小（去掉任何一个顶层键或 model 子字段
 * 都必须被拒，否则探针携带了非必填的伴随字段，被测项的判定同样会被污染）。
 */
export function checkProbeBase(backend, backendKey, base) {
  if (!probePasses(backend, base)) {
    throw new Error(
      `gen-certification: POLICY_PROBE_BASES["${backendKey}"] must pass validateAgentPolicy `
      + "— an invalid probe base would render every verdict as a rejection of something other than the probed item",
    );
  }
  const assertRequired = (label, reduced) => {
    if (probePasses(backend, reduced)) {
      throw new Error(
        `gen-certification: POLICY_PROBE_BASES["${backendKey}"] 底稿字段 ${label} 不是必填 `
        + "（去掉后仍通过）——底稿必须最小，否则探针携带非必填伴随字段",
      );
    }
  };
  for (const key of Object.keys(base)) {
    const reduced = structuredClone(base);
    delete reduced[key];
    assertRequired(key, reduced);
  }
  if (base.model !== null && typeof base.model === "object") {
    for (const key of Object.keys(base.model)) {
      const reduced = structuredClone(base);
      delete reduced.model[key];
      assertRequired(`model.${key}`, reduced);
    }
  }
}

// model 栏的三种探针形状（整体替换底稿的 model；渲染最小可接受写法）。
const MODEL_PROBE_SHAPES = [
  { label: "裸 `{id}`", model: { id: PROBE_MODEL_ID } },
  { label: "`<provider>/<model>` 引用", model: { id: `${PROBE_PROVIDER_ID}/${PROBE_MODEL_ID}` } },
  { label: "`{providerID, id}`", model: { providerID: PROBE_PROVIDER_ID, id: PROBE_MODEL_ID } },
];

/** 底稿深拷贝并整体替换 model。 */
function cloneWithModel(base, model) {
  const agent = structuredClone(base);
  agent.model = structuredClone(model);
  return agent;
}

/**
 * 对一个 backend 跑四轴行为探针（底稿＋单项派生法），返回判定 + 机械可渲染的
 * 条件事实。每个探针都是底稿的深拷贝、只改或只加一项，不改底稿本身。
 */
export function probeExpressivity(backend, { k3ModelId, base, backendKey = "(unnamed)" }) {
  // ---- model：三种形状整体替换底稿的 model；必填/可选由底稿派生。 ----
  const modelResults = MODEL_PROBE_SHAPES.map((s) =>
    probePasses(backend, cloneWithModel(base, s.model)));
  const baseHasModel = Object.hasOwn(base, "model");
  const withoutModel = structuredClone(base);
  delete withoutModel.model;
  const modelRequired = baseHasModel && !probePasses(backend, withoutModel);
  const acceptedShape = MODEL_PROBE_SHAPES.find((_, i) => modelResults[i]) ?? null;
  // 三种预设形状全被拒：可能是该 backend 的 model 要求预设形状之外的东西（例如
  // 新的必填子字段），也可能它真的表达不了 model——探针分不清，所以生成失败，
  // 不渲染"不支持"。真有表达不了 model 的 backend 入册时，再在生成器里显式登记。
  if (acceptedShape === null) {
    throw new Error(
      `gen-certification: none of the model probe shapes (${MODEL_PROBE_SHAPES.map((s) => s.label).join(" / ")}) `
      + `is accepted by "${backendKey}" on top of its POLICY_PROBE_BASES entry — probe coverage is insufficient; `
      + "extend MODEL_PROBE_SHAPES, or, for a backend that truly cannot express any model, add an explicit registration "
      + "to the generator (none exists yet) instead of rendering 不支持",
    );
  }
  // 已证合法的 model：底稿带 model 时用底稿的（保留全部子字段），否则用最小可接受写法；
  // 每个被接受的预设形状也都是合法 model。
  const legalModel = baseHasModel ? base.model : acceptedShape.model;
  const legalModels = [legalModel, ...MODEL_PROBE_SHAPES.filter((_, i) => modelResults[i]).map((s) => s.model)];

  // ---- reasoning：底稿＋单项 effort，逐个探 REASONING_EFFORTS 六值闭集。 ----
  // 每档三种探法：底稿原样加 effort；换上任一已证合法的 model（底稿的 model 与
  // 每个被接受的预设形状）加 effort；把这些合法 model 的 id 换成 K3（保留其它子
  // 字段）加 effort。只有"合法 model 都不行、K3 才行"才算须绑定 K3（kimi 档位门的模型
  // 绑定事实源）。"须带某种合法 model"，或部分档位依赖 K3、部分不依赖，现有渲染
  // 词说不清——生成失败，不猜。
  const withEffort = (agent, effort) => ({ ...agent, reasoning: { effort } });
  const classifyEffort = (effort) => {
    if (probePasses(backend, withEffort(structuredClone(base), effort))) return "plain";
    if (legalModels.some((m) => probePasses(backend, withEffort(cloneWithModel(base, m), effort)))) return "anyModel";
    if (legalModels.some((m) => probePasses(backend, withEffort(cloneWithModel(base, { ...m, id: k3ModelId }), effort)))) return "k3";
    return "rejected";
  };
  const effortClass = new Map(REASONING_EFFORTS.map((effort) => [effort, classifyEffort(effort)]));
  const reasoningAccepted = REASONING_EFFORTS.filter((effort) => effortClass.get(effort) !== "rejected");
  const acceptedKinds = new Set(reasoningAccepted.map((effort) => effortClass.get(effort)));
  if (acceptedKinds.has("anyModel") || (acceptedKinds.has("k3") && acceptedKinds.size > 1)) {
    throw new Error(
      `gen-certification: "${backendKey}" accepts reasoning efforts under model conditions the table cannot render `
      + `(${reasoningAccepted.map((effort) => `${effort}=${effortClass.get(effort)}`).join(", ")}) `
      + "— extend the reasoning rendering instead of guessing",
    );
  }
  const reasoningConditionParts = [
    reasoningAccepted.length > 0 && reasoningAccepted.length < REASONING_EFFORTS.length
      ? `effort ∈ {${reasoningAccepted.join(", ")}}`
      : null,
    acceptedKinds.has("k3") ? `须绑定 ${k3ModelId}` : null,
  ].filter(Boolean);

  // ---- provider：底稿＋provider 块。 ----
  const providerAccepted = probePasses(backend, {
    ...structuredClone(base),
    provider: structuredClone(PROBE_PROVIDER),
  });

  // ---- contextWindow：在已证合法的 model 上只加 contextWindow；provider 被接受时
  // 再探 provider 路径（底稿＋provider 块＋含 contextWindow 的 model）。 ----
  const contextModel = { ...structuredClone(legalModel), contextWindow: PROBE_CONTEXT_WINDOW };
  const contextWindowShapes = [
    { name: "model 路径", agent: cloneWithModel(base, contextModel) },
  ];
  if (providerAccepted) {
    contextWindowShapes.push({
      name: "provider 路径",
      agent: { ...cloneWithModel(base, contextModel), provider: structuredClone(PROBE_PROVIDER) },
    });
  }
  const contextWindowResults = contextWindowShapes.map((s) => probePasses(backend, s.agent));

  return {
    model: {
      verdict: modelRequired ? "必填" : "可选",
      condition: acceptedShape.label,
    },
    reasoning: {
      // 模型绑定条件与档位数量无关：六档全过但都要 K3 时仍是"条件：须绑定 K3"。
      verdict: reasoningAccepted.length === 0
        ? "不支持"
        : reasoningConditionParts.length > 0 ? "条件" : "支持",
      condition: reasoningConditionParts.length > 0 ? reasoningConditionParts.join("，") : null,
    },
    contextWindow: {
      verdict: deriveVerdict(contextWindowResults),
      condition: deriveVerdict(contextWindowResults) === "条件"
        ? `仅 ${contextWindowShapes.filter((_, i) => contextWindowResults[i]).map((s) => s.name).join(" / ")}`
        : null,
    },
    provider: {
      verdict: deriveVerdict([providerAccepted]),
      condition: null,
    },
  };
}

