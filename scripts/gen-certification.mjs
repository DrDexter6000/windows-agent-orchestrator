//   - 每 backend 条件与限制说明：src/backends/factory.js CAPABILITY_NOTES
//     （单一出处，内容自 usage.md 旧表格迁移压缩）。
//   - 认证台账：只放指针（runs/component-checks.json 与
//     runs/reliability-summary.json 是 gitignored 运行时状态，严禁嵌入 live 值）。
//
// 确定性契约（字节钉守卫：本脚本 --check + test/isolation-infra/
