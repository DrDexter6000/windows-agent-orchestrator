//
// Usage: npm run gen:certification            （写出文件）
//        npm run gen:certification -- --check （重渲染与磁盘比对：换行归一化后文本一致，
//        CRLF/LF 视为相同——`.gitattributes` 已钉 docs/surface/*.md eol=lf；不一致 exit 1）

import { mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { KNOWN_BACKENDS, REASONING_EFFORTS } from "../src/registry.js";
import {
  backendFor,
  readBackendCapabilities,
  BACKEND_CAPABILITY_AXES,
  CAPABILITY_NOTES,
} from "../src/backends/factory.js";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CERTIFICATION_MD = "docs/surface/certification.md";
const MARKER = "<!-- GENERATED by scripts/gen-certification.mjs — DO NOT EDIT; run npm run gen:certification -->";
const AUDIENCE = "Audience: repository-level agents and humans; 认证台账 live 值不在本文件（见 §三）。";

// =====================================================================
// 行为探针（TD-162 policy 门守卫的同一套派生法）
// =====================================================================

// 惰性 fetch（探针只调 validateAgentPolicy，构造期与探针期都不发网络请求）。
const PROBE_FETCH_IMPL = async () => ({ ok: true, status: 200, json: async () => ({}) });
const PROBE_PROVIDER = {
  protocol: "anthropic-compatible",
  baseUrl: "https://gen-certification-probe.invalid",
  apiKeyEnv: "GEN_CERTIFICATION_PROBE_KEY",
};

/** 派生法：全过=支持 / 全拒=不支持 / 混合=条件（与退役 TD-162 守卫逐字同款）。 */
function deriveVerdict(results) {
  if (results.every(Boolean)) return "支持";
  if (results.some(Boolean)) return "条件";
  return "不支持";
}

function probePasses(backend, agent) {
  try {
    backend.validateAgentPolicy(agent);
    return true;
  } catch {
    return false;
  }
}

// kimi 档位门的模型绑定事实源：KIMI_K3_MODEL_ID 源常量（提取法沿用退役守卫）。
function extractKimiK3ModelId() {
  const src = readFileSync(join(REPO_ROOT, "src", "backends", "kimiCode.js"), "utf8");
  const id = src.match(/const KIMI_K3_MODEL_ID = "([^"]+)"/)?.[1];
  if (!id) {
    throw new Error("gen-certification: src/backends/kimiCode.js must define KIMI_K3_MODEL_ID (reasoning probe companion source)");
  }
  return id;
}

// opencode-serve 角色合同版本门事实源：OPENCODE_NATIVE_SYSTEM_MIN_VERSION 源常量。
function extractOpencodeMinVersion() {
  const src = readFileSync(join(REPO_ROOT, "src", "backends", "opencodeServe.js"), "utf8");
  const raw = src.match(/OPENCODE_NATIVE_SYSTEM_MIN_VERSION = Object\.freeze\(\[([^\]]*)\]\)/)?.[1];
  if (!raw) {
    throw new Error("gen-certification: src/backends/opencodeServe.js must define OPENCODE_NATIVE_SYSTEM_MIN_VERSION");
  }
  const [maj, min] = [...raw.matchAll(/\d+/g)].map((m) => m[0]);
  return `${maj}.${min}`;
}

// 探针形状名（model 条件格 / contextWindow 条件格的机械渲染词）。
const MODEL_SHAPES = [
  { name: "canonical 裸 `{id}`", agent: { model: { id: "gen-certification-probe-model" } } },
  { name: "OpenCode 形状 `{providerID, id}`", agent: { model: { providerID: "gen-certification-probe", id: "gen-certification-probe-model" } } },
];
const CONTEXT_WINDOW_SHAPES_BASE = [
  { name: "裸 `{contextWindow}`", agent: { model: { contextWindow: 1000000 } } },
  { name: "`{id, contextWindow}`", agent: { model: { id: "gen-certification-probe-model", contextWindow: 1000000 } } },
];
const CONTEXT_WINDOW_PROVIDER_SHAPE = {
  name: "provider 路径",
  agent: { provider: PROBE_PROVIDER, model: { id: "gen-certification-probe-model", contextWindow: 1000000 } },
};

/** 对一个 backend 跑四轴行为探针，返回判定 + 机械可渲染的条件事实。 */
function probeExpressivity(backend, k3ModelId) {
  const providerResults = [PROBE_PROVIDER].map((provider) =>
    probePasses(backend, { provider }));

  const modelResults = MODEL_SHAPES.map((s) => probePasses(backend, s.agent));

  // reasoning：六值闭集逐成员裸探 + 绑定 K3 模型再探（kimi 档位门的事实源）。
  const reasoningAccepted = REASONING_EFFORTS.filter((effort) =>
    probePasses(backend, { reasoning: { effort } })
    || probePasses(backend, { model: { id: k3ModelId }, reasoning: { effort } }));
  const needsModelCompanion = reasoningAccepted.some((effort) =>
    !probePasses(backend, { reasoning: { effort } })
    && probePasses(backend, { model: { id: k3ModelId }, reasoning: { effort } }));

  // contextWindow：裸 + 带模型 id +（provider 合法时）provider 路径伴随。
  const contextWindowShapes = [...CONTEXT_WINDOW_SHAPES_BASE];
  if (providerResults[0]) contextWindowShapes.push(CONTEXT_WINDOW_PROVIDER_SHAPE);
  const contextWindowResults = contextWindowShapes.map((s) => probePasses(backend, s.agent));

  const acceptedShapes = (shapes, results) => shapes.filter((_, i) => results[i]).map((s) => s.name);

  return {
    model: {
      verdict: deriveVerdict(modelResults),
      condition: deriveVerdict(modelResults) === "条件"
        ? `仅 ${acceptedShapes(MODEL_SHAPES, modelResults).join(" / ")}`
        : null,
    },
    reasoning: {
      verdict: deriveVerdict(REASONING_EFFORTS.map((e) => reasoningAccepted.includes(e))),
      condition: reasoningAccepted.length > 0 && reasoningAccepted.length < REASONING_EFFORTS.length
        ? `effort ∈ {${reasoningAccepted.join(", ")}}${needsModelCompanion ? `，须绑定 ${k3ModelId}` : ""}`
        : null,
    },
    contextWindow: {
      verdict: deriveVerdict(contextWindowResults),
      condition: deriveVerdict(contextWindowResults) === "条件"
        ? `仅 ${acceptedShapes(contextWindowShapes, contextWindowResults).join(" / ")}`
        : null,
    },
    provider: {
      verdict: deriveVerdict(providerResults),
      condition: null,
    },
  };
}

// =====================================================================
// 渲染
// =====================================================================

// 四轴 policy 面的条件说明键序（CAPABILITY_NOTES 键 → 展示标签；顺序即渲染顺序）。
const POLICY_NOTE_ORDER = [
  ["model", "model override"],
  ["reasoning", "reasoning effort"],
  ["contextWindow", "model.contextWindow"],
  ["provider", "provider 块"],
];
const AXIS_LABELS = {
  supportsRoleContract: "supportsRoleContract（角色合同）",
  supportsSessionReuse: "supportsSessionReuse（会话复用）",
  supportsInFlightCorrection: "supportsInFlightCorrection（在途纠偏）",
  replayByRespawn: "replayByRespawn（重放=重生）",
  reportsTokenUsage: "reportsTokenUsage（token usage）",
  reportsCommandExitCode: "reportsCommandExitCode（命令退出码）",
};

/** 六轴 ✅/—（strict === true，声明闭集投影）。 */
function capabilityCell(declared) {
  return declared ? "✅" : "—";
}

/** 四轴判定格：判定词（探针派生）＋ 条件（探针机械渲染）。 */
function verdictCell({ verdict, condition }) {
  return condition === null ? verdict : `${verdict}：${condition}`;
}

/**
 * 渲染 docs/surface/certification.md 全文。同步、纯（相对工作树零写入、零
 * spawn、零网络）；同输入 ⇒ 逐字节相同输出。
 *
 * @returns {string}
 */
export function renderCertification() {
  const k3ModelId = extractKimiK3ModelId();
  const opencodeMinVersion = extractOpencodeMinVersion();

  // CAPABILITY_NOTES 键集守卫（生成期红，不静默）：闭集成员必须有登记（可为
  // 空对象），闭集外不得有孤儿键；opencode 版本门注记必须含源常量派生的
  // `maj.min`（注记漂移即生成失败——退役守卫同款锚定纪律）。
  const noteKeys = Object.keys(CAPABILITY_NOTES).sort();
  const backendKeys = [...KNOWN_BACKENDS].sort();
  if (JSON.stringify(noteKeys) !== JSON.stringify(backendKeys)) {
    throw new Error(
      "gen-certification: CAPABILITY_NOTES key set must equal KNOWN_BACKENDS exactly "
      + `(notes: [${noteKeys.join(", ")}] vs backends: [${backendKeys.join(", ")}]) — 新 backend 增补属 Owner 决策，落库时同步登记条件说明`,
    );
  }
  const opencodeRoleNote = CAPABILITY_NOTES["opencode-serve"]?.supportsRoleContract ?? "";
  if (!opencodeRoleNote.includes(opencodeMinVersion)) {
    throw new Error(
      `gen-certification: opencode-serve supportsRoleContract note must carry the version gate ${opencodeMinVersion} derived from OPENCODE_NATIVE_SYSTEM_MIN_VERSION (note drifted)`,
    );
  }

  // 探针（共享工厂构造——构造期零副作用；validateAgentPolicy 是纯校验）。
  const rows = KNOWN_BACKENDS.map((backendKey) => {
    const backend = backendFor(
      { backend: backendKey, cwd: "D:/gen-certification/probe" },
      { fetchImpl: PROBE_FETCH_IMPL },
    );
    return {
      backendKey,
      capabilities: readBackendCapabilities(backend),
      expressivity: probeExpressivity(backend, k3ModelId),
    };
  });

  const lines = [];
  lines.push(MARKER);
  lines.push("# WAO backend 能力与配置表达力（认证事实生成层，TD-162）");
  lines.push("");
  lines.push(AUDIENCE);
  lines.push("");
  lines.push("数据源（现成 SSOT，本文件不含第二真相）：");
  lines.push("");
  lines.push("- 六轴能力：`src/registry.js` `KNOWN_BACKENDS` × `src/backends/factory.js` `BACKEND_CAPABILITY_AXES` / `readBackendCapabilities`（strict `=== true`——未声明读 false，fail-closed）。");
  lines.push("- 配置表达力四轴：对经共享工厂构造的 backend 实例调用 `validateAgentPolicy` 的**行为探针**派生（判定法沿用退役 TD-162 policy 门守卫的同一套派生法；kimi 档位绑定模型提取自 `src/backends/kimiCode.js` `KIMI_K3_MODEL_ID` 源常量）。");
  lines.push("- 每 backend 条件与限制说明：`src/backends/factory.js` `CAPABILITY_NOTES`（单一出处，§二之末逐条渲染）。");
  lines.push("");
  lines.push("漂移纪律：判定词与档位集合**只在生成期从代码派生**；磁盘副本由字节钉守卫（`npm run gen:certification -- --check` + `test/isolation-infra/docsSurface.test.js` + `test/isolation-infra/docs-consistency.test.js` 的 TD-162 生成物守卫）钉住。**守卫的实际保证是「换行归一化后文本一致」**（CRLF/LF 视为相同——`.gitattributes` 已钉 `docs/surface/*.md eol=lf`），不是原始字节相等；入口检测失败时 `--check` fail-closed（exit 1），绝不静默跳过——改 backend 代码/`CAPABILITY_NOTES` 后须 `npm run gen:certification` 再生成并提交。");
  lines.push("");
  lines.push("## 一、六轴能力闭集声明（strict === true）");
  lines.push("");
  lines.push(`| backend | ${BACKEND_CAPABILITY_AXES.join(" | ")} |`);
  lines.push(`| --- | ${BACKEND_CAPABILITY_AXES.map(() => "---").join(" | ")} |`);
  for (const row of rows) {
    lines.push(`| ${row.backendKey} | ${BACKEND_CAPABILITY_AXES.map((axis) => capabilityCell(row.capabilities[axis])).join(" | ")} |`);
  }
  lines.push("");
  lines.push("✅ = 类声明 `=== true`；— = **未声明或非严格 true**（strict `=== true` 读取为 false——两者同格，例如 deepseek-acp 多轴是显式声明 `false`）。带条件/限制的轴（如 opencode-serve 角色合同的版本门）见 §二条件与限制说明。");
  lines.push("");
  lines.push("## 二、配置表达力四轴判定（validateAgentPolicy 行为探针派生）");
  lines.push("");
  lines.push("判定词（只管 **WAO 接线层**）：**支持**＝全部探针通过；**不支持**＝全部探针被 `validateAgentPolicy` 拒绝（fail-closed 硬拒，不是静默忽略——成因三分：上游无此能力 / 上游有原语但 WAO 未接线 / 配置形状不一致被拒，逐条事实见 `docs/usage.md`「上游 harness 原语对照（实测）」节）；**条件**＝部分探针通过（条件写在格内，探针派生）。");
  lines.push("");
  lines.push("| backend | model override（model.id / --model） | reasoning effort | model.contextWindow | provider 块 |");
  lines.push("| --- | --- | --- | --- | --- |");
  for (const row of rows) {
    const cells = [
      verdictCell(row.expressivity.model),
      verdictCell(row.expressivity.reasoning),
      verdictCell(row.expressivity.contextWindow),
      verdictCell(row.expressivity.provider),
    ];
    lines.push(`| ${row.backendKey} | ${cells.join(" | ")} |`);
  }
  lines.push("");
  lines.push("衔接：per-dispatch `--model` 只替换 `model.id`、兄弟字段保留——opencode-serve 的 agent 必须先带 `providerID`；`--reasoning` 的六值闭集（minimal/low/medium/high/xhigh/max）由 `registry.js` `REASONING_EFFORTS` 在 registry 层校验，backend 层再按上表条件格收窄。");
  lines.push("");
  lines.push("### 条件与限制说明（CAPABILITY_NOTES 单一出处：src/backends/factory.js）");
  lines.push("");
  for (const row of rows) {
    lines.push(`- **${row.backendKey}**`);
    for (const [key, label] of POLICY_NOTE_ORDER) {
      const note = CAPABILITY_NOTES[row.backendKey]?.[key];
      if (note) lines.push(`  - ${label}：${note}`);
    }
    for (const axis of BACKEND_CAPABILITY_AXES) {
      const note = CAPABILITY_NOTES[row.backendKey]?.[axis];
      if (note) lines.push(`  - ${AXIS_LABELS[axis]}：${note}`);
    }
  }
  lines.push("");
  lines.push("## 三、认证台账（指针；严禁嵌入 live 值）");
  lines.push("");
  lines.push("- **组件层台账**：`runs/component-checks.json`（gitignored 运行时状态）——backend/llm 单独验证记录（组件键含 runtimeIdentity 指纹，版本漂移降 advisory）。刷新：`npm run component-check`。");
  lines.push("- **组合层台账**：`runs/reliability-summary.json`（gitignored 运行时状态）——按席位 agentId 的 certified/conditional/draft-only 台账。刷新：`npm run reliability`。");
  lines.push("- 台账是**运行时状态**，由上述命令产出与刷新；本生成文件只承载静态能力/配置表达力事实（§一/§二）——嵌入台账 live 值会把它变成会过期的快照，禁止。");
  lines.push("- 认证检查结果五态判定纪律（pass / fail / not-applicable / blocked / inconclusive）与能力轴分层：`docs/usage.md`（ADR-0032 §8 节）；两层认证决策：`.wao/decisions/0032-两层验证与认证.md`。");
  return lines.join("\n") + "\n";
}

// 写出/校验仅在作为主模块运行时发生（import 永不写入）。
// F1（2026-09-22 auditor 审计修复）：`import.meta.main` 直到 Node 22.18 才加入，而
// package.json 允许整个 Node 22 系列——更早的 22.x 上该属性为 undefined，整块写出/校验
// 会被静默跳过（fail-open：过期/缺失的生成物也 exit 0）。改用 argv[1] ↔ import.meta.url
// 的兼容比对，并在「看起来是被当脚本调用、却判定不是主模块」时 fail-closed 直接 exit 1。
// N1（2026-09-22 窄复核修复）：判据**不得**是"文件名后缀"——那会把合法 import 误杀
// （例如 `my-gen-certification.mjs` 或同名包装脚本导入时 exit 1，实测已发生）。
// 只在"**确实是同一个文件**、URL 比对却失败"时才 fail-closed；非本文件一律按 import 处理。
const ENTRY_ARG = typeof process.argv[1] === "string" ? process.argv[1] : "";
let isMainModule = false;
let sameFileByRealpath = false;
if (ENTRY_ARG.length > 0) {
  try {
    isMainModule = pathToFileURL(resolve(ENTRY_ARG)).href === import.meta.url;
  } catch {
    isMainModule = false;
  }
  try {
    sameFileByRealpath = realpathSync(resolve(ENTRY_ARG)) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    sameFileByRealpath = false;
  }
}
if (!isMainModule && sameFileByRealpath) {
  console.error("[gen-certification] entry-point detection failed on the same file — refusing to exit 0 without checking (fail-closed)");
  process.exit(1);
}
if (isMainModule) {
  const target = join(REPO_ROOT, CERTIFICATION_MD);
  const rendered = renderCertification();
  if (process.argv.includes("--check")) {
    let onDisk;
    try {
      onDisk = readFileSync(target, "utf8");
    } catch {
      console.error(`[gen-certification] ${CERTIFICATION_MD} does not exist — run npm run gen:certification and commit the output`);
      process.exit(1);
    }
    if (onDisk.replace(/\r\n/g, "\n") !== rendered) {
      console.error(`[gen-certification] ${CERTIFICATION_MD} is stale — run npm run gen:certification and commit the output`);
      process.exit(1);
    }
    console.log(`[gen-certification] ${CERTIFICATION_MD} is up to date (${Buffer.byteLength(rendered, "utf8")} bytes)`);
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, rendered, "utf8");
    console.log(`[gen-certification] wrote ${CERTIFICATION_MD} (${Buffer.byteLength(rendered, "utf8")} bytes)`);
  }
}
