// =====================================================================
// TOKEN never appears in ANY response body or header (sweep)
// =====================================================================
test("TOKEN: never present in any response body or header value across all outcomes", async () => {
  const s = makeServer();
  const auth = { authorization: "Bearer " + s.token };
  const cases = [
    { url: "/health" },
    { url: "/" }, // 302
    { url: "/v2" },
    { url: "/api/overview", headers: auth }, // 200 loading
    { url: "/api/overview" }, // 401
    { url: "/api/workers?project=bad/slug", headers: auth }, // 400
    { url: "/nope" }, // 404
    { url: "/api/runs", headers: auth }, // 404 (retired)
    { method: "POST", url: "/api/overview", headers: auth }, // 405
  ];
  for (const c of cases) {
    const r = await drive(s.handler, c);
    assert.ok(!r.body.includes(s.token), `token absent from body (${c.method || "GET"} ${c.url})`);
    assert.ok(!JSON.stringify(r.headers).includes(s.token), `token absent from headers (${c.method || "GET"} ${c.url})`);
    assertSafeHeaders(r, null); // the content type differs per outcome (/v2 is HTML); only the safe headers are common
  }
});

// =====================================================================
// TOKEN CONTRACT — always exactly 64 lowercase hex derived from 32 bytes
// =====================================================================
test("TOKEN CONTRACT: issued token is exactly 64 lowercase hex derived from the injected 32-byte entropy", () => {
  // Entropy input contract: injected bytes deterministically produce the token.
  const ab = makeServer({ randomBytesFn: () => Buffer.alloc(32, 0xab) });
  assert.equal(ab.token, "ab".repeat(32), "deterministic bytes → hex");
  assert.equal(ab.token.length, 64);
  assert.match(ab.token, /^[0-9a-f]{64}$/);

  // Different injected bytes → different token.
  const cd = makeServer({ randomBytesFn: () => Buffer.alloc(32, 0xcd) });
  assert.equal(cd.token, "cd".repeat(32));
  assert.notEqual(ab.token, cd.token);

  // The generator receives the size argument (crypto.randomBytes shape): 32.
  let observedSize = null;
  makeServer({ randomBytesFn: (n) => { observedSize = n; return Buffer.alloc(n, 0x01); } });
  assert.equal(observedSize, 32);

  // Production default (no injection) → valid shape; two issuances differ.
  const d1 = makeServer();
  const d2 = makeServer();
  assert.match(d1.token, /^[0-9a-f]{64}$/);
  assert.match(d2.token, /^[0-9a-f]{64}$/);
  assert.notEqual(d1.token, d2.token, "default entropy is crypto-random, not constant");
});

test("TOKEN AUTHORITY: invalid randomBytesFn output rejected fail-closed before any side effect", () => {
  const bad = [
    () => Buffer.alloc(16),                  // too few bytes
    () => Buffer.alloc(64),                  // too many bytes
    () => Buffer.alloc(0),                   // zero bytes
    () => 12345,                             // not bytes (number)
    () => "not-bytes",                       // not bytes (string)
    () => null,                              // not bytes (null)
    () => { throw new Error("no entropy"); },// generator throws
  ];
  for (const fn of bad) {
    assert.throws(
      () => makeServer({ randomBytesFn: fn }),
      /invalid|random source|token/i,
      `rejects generator: ${fn.toString().slice(0, 48)}`,
    );
  }
});

