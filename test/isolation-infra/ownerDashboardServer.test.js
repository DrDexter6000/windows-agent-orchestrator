// test/ownerDashboardServer.test.js
//
// The ownerDashboardServer loopback HTTP boundary (M12-8C; batch 145a retired the
// legacy UI and its two data routes).
//
// The server is tested via its request HANDLER directly with a fake req/res (no
// real socket, no fs, no git) so every boundary rule is asserted deterministically:
//   - bearer required for every data route (no/malformed/wrong → fixed 401, token
//     never in body),
//   - bind 127.0.0.1 only + port 0|1024..65535, any other host/port rejected BEFORE listen,
//   - GET only (other methods → 405), unknown route → fixed 404,
//   - 145a: the retired "/" and "/index.html" answer 302 → /v2/ (empty body, safe headers);
//     the retired UI files and /api/runs + /api/activity are gone,
//   - mandatory safe headers (no-store/nosniff/no-referrer/CSP) and NO CORS opt-in.
//
// Batch 140c: the three read-model routes /api/overview, /api/workers and
// /api/attention are positive cases here; their full contract — auth, closed
// query set, loading → ready → stale, DTO whitelists, the refresh chain, close()
// — lives in ownerDashboardApi.test.js. The import contract below pins the
// server's exact import set.

import { test } from "node:test";
import assert from "node:assert/strict";
import { join } from "node:path";

import { createOwnerDashboardServer } from "../../src/ownerDashboardServer.js";

// ===== Fake req/res + drive helper (pure, in-memory) =====

function drive(handler, { method = "GET", url = "/", headers = {} } = {}) {
  const req = { method, url, headers: { ...headers } };
  const state = { statusCode: 200, headers: {}, body: "", ended: false };
  const res = {
    setHeader(k, v) { state.headers[String(k).toLowerCase()] = v; },
    writeHead(status) { state.statusCode = status; },
    write(c) { state.body += typeof c === "string" ? c : Buffer.from(c).toString("utf8"); },
    end(c) { if (c !== undefined) this.write(c); state.ended = true; },
    getHeader(k) { return state.headers[String(k).toLowerCase()]; },
  };
  const p = handler(req, res);
  return Promise.resolve(p).then(() => ({
    status: state.statusCode, headers: state.headers, body: state.body, ended: state.ended,
  }));
}
const jsonOf = (r) => JSON.parse(r.body);

// Build a server with deterministic config. The token is generated by the factory
// (exercising the real bearer path); tests read it back via .token.
function makeServer({ host, port, randomBytesFn, createReadModelFn } = {}) {
  return createOwnerDashboardServer({
    runDir: "/server/owned/runs",
    env: {},
    ...(host !== undefined ? { host } : {}),
    ...(port !== undefined ? { port } : {}),
    ...(randomBytesFn !== undefined ? { randomBytesFn } : {}),
    ...(createReadModelFn !== undefined ? { createReadModelFn } : {}),
    nowFn: () => 1_000_000,
  });
}

// Assert the common safe headers are present and CORS is NOT opted into.
function assertSafeHeaders(r, contentType = "application/json; charset=utf-8") {
  assert.equal(r.headers["cache-control"], "no-store");
  assert.equal(r.headers["x-content-type-options"], "nosniff");
  assert.equal(r.headers["referrer-policy"], "no-referrer");
  assert.ok(r.headers["content-security-policy"], "CSP set");
  assert.ok(!("access-control-allow-origin" in r.headers), "no CORS opt-in (no ACAO)");
  if (contentType !== null) assert.equal(r.headers["content-type"], contentType);
}

// =====================================================================
// BEARER — required for every data route; no/malformed/wrong → fixed 401
// =====================================================================
test("BEARER: /api/overview with no Authorization → 401 unauthorized, token never in body", async () => {
  const s = makeServer();
  const r = await drive(s.handler, { url: "/api/overview" });
  assert.equal(r.status, 401);
  assert.deepEqual(jsonOf(r), { error: "unauthorized" });
  assertSafeHeaders(r);
  assert.ok(!r.body.includes(s.token), "token never in body");
  assert.ok(!JSON.stringify(r.headers).includes(s.token), "token never in headers");
});

test("BEARER: malformed Authorization (not 'Bearer ...') → 401", async () => {
  const s = makeServer();
  for (const h of [
    { authorization: s.token }, // missing scheme
    { authorization: "Basic " + s.token }, // wrong scheme
    { authorization: "Bearer" }, // no value
    { authorization: "Bearer  " }, // empty value
    { authorization: "bearer " + s.token }, // lowercase scheme is NOT accepted (strict)
  ]) {
    const r = await drive(s.handler, { url: "/api/overview", headers: h });
    assert.equal(r.status, 401, `401 for ${JSON.stringify(h)}`);
    assert.deepEqual(jsonOf(r), { error: "unauthorized" });
  }
});

test("BEARER: wrong token → 401 (timing-safe compare, token never in body)", async () => {
  const s = makeServer();
  const r = await drive(s.handler, { url: "/api/overview", headers: { authorization: "Bearer " + "0".repeat(s.token.length) } });
  assert.equal(r.status, 401);
  assert.deepEqual(jsonOf(r), { error: "unauthorized" });
  assert.ok(!r.body.includes(s.token));
});

test("BEARER: correct token → 200; /health needs no token", async () => {
  const s = makeServer();
  const ok = await drive(s.handler, { url: "/api/overview", headers: { authorization: "Bearer " + s.token } });
  assert.equal(ok.status, 200);
  const health = await drive(s.handler, { url: "/health" });
  assert.equal(health.status, 200);
  assert.deepEqual(jsonOf(health), { status: "ok" });
});

// =====================================================================
// HOST / PORT — reject non-loopback host + invalid port BEFORE listen
// =====================================================================
test("HOST: only 127.0.0.1 accepted; any other host rejected before listen", () => {
  for (const host of ["0.0.0.0", "::1", "localhost", "192.168.1.1", "", "127.0.0.2"]) {
    assert.throws(
      () => makeServer({ host }),
      /host|loopback|127/i,
      `rejects host ${JSON.stringify(host)} before listen`,
    );
  }
  // Valid default + explicit loopback do not throw.
  assert.doesNotThrow(() => makeServer({}));
  assert.doesNotThrow(() => makeServer({ host: "127.0.0.1" }));
});

test("PORT: 0 or 1024..65535 accepted; anything else rejected before listen", () => {
  for (const port of [80, 443, 1023, 65536, 70000, -1, 1.5, "8080", NaN, Infinity, null]) {
    assert.throws(
      () => makeServer({ port }),
      /port/i,
      `rejects port ${JSON.stringify(port)} before listen`,
    );
  }
  for (const port of [0, 1024, 8080, 65535]) {
    assert.doesNotThrow(() => makeServer({ port }), `accepts port ${port}`);
  }
  // undefined port → default (0), no throw.
  assert.doesNotThrow(() => makeServer({}));
});

// =====================================================================
// METHOD — GET only; everything else → 405 with Allow: GET
// =====================================================================
test("METHOD: non-GET → 405 with Allow: GET (incl. OPTIONS = no CORS)", async () => {
  const s = makeServer();
  for (const method of ["POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"]) {
    const r = await drive(s.handler, { method, url: "/api/overview", headers: { authorization: "Bearer " + s.token } });
    assert.equal(r.status, 405, `${method} → 405`);
    assert.equal(r.headers.allow, "GET");
    assert.deepEqual(jsonOf(r), { error: "method_not_allowed" });
    assertSafeHeaders(r);
    // OPTIONS must NOT opt into CORS.
    assert.ok(!("access-control-allow-origin" in r.headers));
  }
});

// =====================================================================
// ROUTE — the retired entry redirects; unknown routes are fixed 404s
// =====================================================================
test("ROUTE (145a): / and /index.html → 302 /v2/ with safe headers and no body; the retired files and data routes are 404", async () => {
  const s = makeServer();
  for (const url of ["/", "/index.html"]) {
    const r = await drive(s.handler, { url });
    assert.equal(r.status, 302, url);
    assert.equal(r.headers.location, "/v2/");
    assert.equal(r.body, "", "no body");
    assert.equal(Number(r.headers["content-length"]), 0);
    assertSafeHeaders(r);
    assert.ok(!JSON.stringify(r.headers).includes(s.token), "no token in the redirect");
  }
  // The v2 page is the one entry that serves HTML.
  const page = await drive(s.handler, { url: "/v2/" });
  assert.equal(page.status, 200);
  assert.equal(page.headers["content-type"], "text/html; charset=utf-8");
  assert.equal(page.headers["cache-control"], "no-store");
  // The retired assets and data routes are gone (fixed 404, no auth probe).
  for (const url of ["/app.js", "/styles.css", "/api/runs", "/api/activity", "/api/runs/extra"]) {
    const r = await drive(s.handler, { url });
    assert.equal(r.status, 404, `${url} → 404`);
    assert.deepEqual(jsonOf(r), { error: "not_found" });
    assertSafeHeaders(r);
  }
  for (const url of ["/unknown", "/api/foo", "/api/"]) {
    const r = await drive(s.handler, { url });
    assert.equal(r.status, 404, `${url} → 404`);
    assert.deepEqual(jsonOf(r), { error: "not_found" });
  }
});

// =====================================================================
// ROUTE (140c) — the three read-model routes are served (positive cases)
// =====================================================================
test("ROUTE (140c): /api/overview, /api/workers, /api/attention → 200; loading until refreshNow(), then ready", async () => {
  let refreshes = 0;
  const NOW = 1_000_000;
  const s = makeServer({
    createReadModelFn: () => ({
      refresh: async () => { refreshes += 1; },
      snapshot: ({ now }) => ({ generatedAt: new Date(now).toISOString(), projects: [], runs: [], consults: [] }),
    }),
  });
  const auth = { authorization: "Bearer " + s.token };
  const routes = ["/api/overview", "/api/workers", "/api/attention"];
  for (const url of routes) {
    const loading = await drive(s.handler, { url, headers: auth });
    assert.equal(loading.status, 200, `${url} → 200 (not 404)`);
    assert.deepEqual(jsonOf(loading), { status: "loading" }, "no data before the first refresh");
    assertSafeHeaders(loading);
    const unauthorized = await drive(s.handler, { url });
    assert.equal(unauthorized.status, 401, `${url} without bearer → 401`);
  }
  assert.equal(refreshes, 0, "nothing refreshes until listen() / refreshNow()");
  assert.equal(await s.refreshNow(), "ready");
  assert.equal(refreshes, 1);
  const generatedAt = new Date(NOW).toISOString();
  const overview = jsonOf(await drive(s.handler, { url: "/api/overview", headers: auth }));
  assert.equal(overview.status, "ready");
  assert.deepEqual(overview.counts, {
    running: 0, starting: 0,
    liveness: { terminal: 0, progress: 0, process_only: 0, silent: 0, unknown: 0 },
    verifying: 0, deliveryUnobservable: 0, decide: { open: 0, unknown: 0 }, anomalies: { open: 0, unknown: 0 },
  });
  assert.deepEqual(overview.projects, []);
  assert.deepEqual(overview.lanes, []);
  assert.deepEqual(jsonOf(await drive(s.handler, { url: "/api/workers", headers: auth })),
    { status: "ready", generatedAt, truncated: false, workers: [] });
  assert.deepEqual(jsonOf(await drive(s.handler, { url: "/api/attention", headers: auth })),
    { status: "ready", generatedAt, decide: [], anomalies: [], resolved: [] });
});

