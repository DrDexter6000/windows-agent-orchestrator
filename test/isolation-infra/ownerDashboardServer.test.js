// =====================================================================
// TOKEN CONTRACT — always exactly 64 lowercase hex derived from 32 bytes
// =====================================================================
test("TOKEN CONTRACT: issued token is exactly 64 lowercase hex derived from the injected 32-byte entropy", () => {
  // Entropy input contract: injected bytes deterministically produce the token.
  const ab = makeServer({ randomBytesFn: () => Buffer.alloc(32, 0xab) });
  assert.equal(ab.token, "ab".repeat(32), "deterministic bytes → hex");
  assert.equal(ab.token.length, 64);
  assert.match(ab.token, /^[0-9a-f]{64}$/);

  // Different injected bytes → different token.
  const cd = makeServer({ randomBytesFn: () => Buffer.alloc(32, 0xcd) });
  assert.equal(cd.token, "cd".repeat(32));
  assert.notEqual(ab.token, cd.token);

  // The generator receives the size argument (crypto.randomBytes shape): 32.
  let observedSize = null;
  makeServer({ randomBytesFn: (n) => { observedSize = n; return Buffer.alloc(n, 0x01); } });
  assert.equal(observedSize, 32);

  // Production default (no injection) → valid shape; two issuances differ.
  const d1 = makeServer();
  const d2 = makeServer();
  assert.match(d1.token, /^[0-9a-f]{64}$/);
  assert.match(d2.token, /^[0-9a-f]{64}$/);
  assert.notEqual(d1.token, d2.token, "default entropy is crypto-random, not constant");
});

