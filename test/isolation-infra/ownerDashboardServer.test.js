// ===== Fake req/res + drive helper (pure, in-memory) =====

function drive(handler, { method = "GET", url = "/", headers = {} } = {}) {
  const req = { method, url, headers: { ...headers } };
  const state = { statusCode: 200, headers: {}, body: "", ended: false };
  const res = {
    setHeader(k, v) { state.headers[String(k).toLowerCase()] = v; },
    writeHead(status) { state.statusCode = status; },
    write(c) { state.body += typeof c === "string" ? c : Buffer.from(c).toString("utf8"); },
    end(c) { if (c !== undefined) this.write(c); state.ended = true; },
    getHeader(k) { return state.headers[String(k).toLowerCase()]; },
  };
  const p = handler(req, res);
  return Promise.resolve(p).then(() => ({
    status: state.statusCode, headers: state.headers, body: state.body, ended: state.ended,
  }));
}
const jsonOf = (r) => JSON.parse(r.body);

// Build a server with deterministic service fakes. The token is generated by
// the factory (exercising the real bearer path); tests read it back via .token.
function makeServer({ runsFn, activityFn, host, port, randomBytesFn } = {}) {
  const runs = runsFn ?? (async () => ({ runs: [], returnedCount: 0, matchedCount: 0, truncated: false }));
  const activity = activityFn ?? (async () => ({
    runId: "run_x", available: true, unavailableReason: null,
    activity: { entries: [], total: 0, counts: {}, nextCursor: null },
    liveness: { ownerHeartbeat: "n/a", secondsSinceHeartbeat: null },
  }));
  return createOwnerDashboardServer({
    runDir: "/server/owned/runs", workspaceRoot: "/server/owned/ws",
    knownAgentIds: ["coder_low"], env: {},
    ...(host !== undefined ? { host } : {}),
    ...(port !== undefined ? { port } : {}),
    ...(randomBytesFn !== undefined ? { randomBytesFn } : {}),
    getOwnerRunsFn: runs, getOwnerActivityFn: activity,
    nowFn: () => 1_000_000,
  });
}

// Assert the common safe headers are present and CORS is NOT opted into.
function assertSafeHeaders(r) {
  assert.equal(r.headers["cache-control"], "no-store");
  assert.equal(r.headers["x-content-type-options"], "nosniff");
  assert.equal(r.headers["referrer-policy"], "no-referrer");
  assert.ok(r.headers["content-security-policy"], "CSP set");
  assert.ok(!("access-control-allow-origin" in r.headers), "no CORS opt-in (no ACAO)");
  assert.equal(r.headers["content-type"], "application/json; charset=utf-8");
}

